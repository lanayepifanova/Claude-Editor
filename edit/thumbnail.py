#!/usr/bin/env python3
"""YouTube thumbnails for the Ignite interviews, modelled on her approved
example (footage/Silicon Data Thumbnails/Silicon Data Thumbnail - Text.jpg):
a frame of the speaker filling 1280x720, the Silicon Data pill top-left, the
Compute Exchange pill top-right, and a two-line condensed-caps headline in navy
on bright green boxes, centred in the lower third.

    python3 edit/thumbnail.py edit/thumbs-ignite.json            # all
    python3 edit/thumbnail.py edit/thumbs-ignite.json --only 12  # one

Config: {"thumbs": [{"nn": "12", "slug": "steven-aravindh", "t": 518.0,
          "lines": ["THE NETWORK IS", "THE BOTTLENECK"], "zoom": 1.15}, ...]}
`t` is the source time of the frame; `zoom` and `x` (face centre in source
pixels) are optional, and x defaults to the largest face Haar finds.

Per video it writes a HyperFrames project in graphics/thumbs/ignite-NN/ and
snapshots it to output/thumbnails/ignite-NN-<slug>.jpg.
"""
import argparse, glob, html, json, os, shutil, subprocess, sys

import cv2
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FOOTAGE = os.path.join(ROOT, "footage", "Ignite Oct 2026")
ASSETS = os.path.join(ROOT, "graphics", "thumbs", "assets")
FONT = os.path.join(ROOT, "graphics", "fonts", "BebasNeue-Regular.ttf")
CASCADE = "/opt/homebrew/share/opencv4/haarcascades/haarcascade_frontalface_default.xml"
W, H = 1280, 720
TOP, ACTIVE = 34, 1012          # baked-in letterbox: picture rows 34-1046

GREEN, NAVY = "#00DE88", "#232234"   # sampled from her example

PAGE = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <title>thumbnail</title>
    <style>
      @font-face {{ font-family: "Bebas Neue"; src: url("BebasNeue-Regular.ttf") format("truetype"); }}
      * {{ margin:0; padding:0; box-sizing:border-box; }}
      html, body {{ width:{W}px; height:{H}px; overflow:hidden; background:#000; }}
      #root {{ position:relative; width:{W}px; height:{H}px; }}
      #bg {{ position:absolute; inset:0; width:{W}px; height:{H}px; }}
      .pill {{ position:absolute; top:24px; border-radius:10px; overflow:hidden; display:block; }}
      .pill.sd {{ left:24px; width:188px; height:54px; }}
      .pill.ce {{ right:24px; width:187px; height:52px; }}
      .head {{ position:absolute; left:0; right:0; bottom:40px; display:flex;
               flex-direction:column; align-items:center; gap:2px; }}
      .line {{ background:{GREEN}; color:{NAVY}; font-family:"Bebas Neue", sans-serif;
               font-size:{size}px; line-height:0.86; padding:12px 18px 2px; letter-spacing:0.01em;
               white-space:nowrap; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="1"
         data-width="{W}" data-height="{H}" data-fps="30">
      <img id="bg" src="bg.jpg" alt="" />
      <img class="pill sd" src="silicon-data.png" alt="" />
      <img class="pill ce" src="compute-exchange.png" alt="" />
      <div class="head">
{lines}
      </div>
    </div>
    <script>
      // GENERATED by edit/thumbnail.py — do not hand-edit.
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = {{ duration: () => 1, seek: () => {{}}, pause: () => {{}}, play: () => {{}},
                                       time: () => 0, totalDuration: () => 1 }};
    </script>
  </body>
</html>
"""


def source(nn):
    hits = glob.glob(os.path.join(FOOTAGE, f"{nn} *.mp4"))
    if len(hits) != 1:
        sys.exit(f"ignite {nn}: expected one source file, found {hits}")
    return hits[0]


def grab(src, t):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-ss", f"{t:.3f}", "-i", src, "-frames:v", "1",
                          "-f", "rawvideo", "-pix_fmt", "bgr24", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(1080, 1920, 3)


def face_x(img):
    g = cv2.cvtColor(img[TOP:TOP + ACTIVE], cv2.COLOR_BGR2GRAY)
    faces = cv2.CascadeClassifier(CASCADE).detectMultiScale(g, 1.1, 6, minSize=(90, 90))
    if not len(faces):
        return None
    x, y, w, h = max(faces, key=lambda f: f[2] * f[3])
    return x + w / 2


def build(th, out_dir):
    nn = th["nn"]
    img = grab(source(nn), th["t"])
    cx = th.get("x") or face_x(img) or 960
    zoom = th.get("zoom", 1.15)
    ch = int(ACTIVE / zoom) // 2 * 2
    cw = int(round(ch * 16 / 9)) // 2 * 2
    x0 = int(min(max(cx - cw / 2, 0), 1920 - cw))
    y0 = TOP + int((ACTIVE - ch) * 0.3)        # keep head room, lose some lap
    crop = img[y0:y0 + ch, x0:x0 + cw]
    proj = os.path.join(ROOT, "graphics", "thumbs", f"ignite-{nn}")
    os.makedirs(proj, exist_ok=True)
    cv2.imwrite(os.path.join(proj, "bg.jpg"),
                cv2.resize(crop, (W, H), interpolation=cv2.INTER_LANCZOS4),
                [cv2.IMWRITE_JPEG_QUALITY, 97])
    for f in ("silicon-data.png", "compute-exchange.png"):
        shutil.copy(os.path.join(ASSETS, f), proj)
    shutil.copy(FONT, proj)
    lines = "\n".join(f'        <div class="line">{html.escape(l).replace("&#x27;", "&#8217;")}</div>'
                      for l in th["lines"])
    with open(os.path.join(proj, "index.html"), "w") as fh:
        fh.write(PAGE.format(W=W, H=H, GREEN=GREEN, NAVY=NAVY, size=th.get("size", 100), lines=lines))
    snap = os.path.join(proj, ".snap")
    shutil.rmtree(snap, ignore_errors=True)
    subprocess.run(["npx", "hyperframes", "snapshot", proj, "--at", "0.5", "--no-end", "--keep",
                    "-o", snap], check=True, stdin=subprocess.DEVNULL, capture_output=True)
    png = glob.glob(os.path.join(snap, "*.png"))[0]
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, f"ignite-{nn}-{th['slug']}.jpg")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", png, "-vf", f"scale={W}:{H}",
                    "-q:v", "2", out], check=True, stdin=subprocess.DEVNULL)
    print(f"ignite {nn}: face x {cx:.0f}, crop {cw}x{ch}+{x0}+{y0} -> {out}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("config")
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--out", default=os.path.join(ROOT, "output", "thumbnails"))
    a = ap.parse_args()
    for th in json.load(open(a.config))["thumbs"]:
        if not a.only or th["nn"] in a.only:
            build(th, a.out)


if __name__ == "__main__":
    main()
