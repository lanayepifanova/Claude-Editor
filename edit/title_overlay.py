#!/usr/bin/env python3
"""Two-line title bubble for a vertical short — the short's hook ("NO WAY TO /
SHORT COMPUTE") held on screen just above the burned-in captions, in the same
look as the Silicon Data thumbnail: condensed caps on solid boxes, one box per
line.

    python3 edit/title_overlay.py --lines "No way to" "short compute" \
        --frames 1157 --out graphics/kc-short1-title
    (cd graphics/kc-short1-title && npx hyperframes render . --format mov -q high \
        -f 24000/1001 --workers 1 -o ../kc-short1-title.mov)

Then stack it under the captions in burn.py (overlays are given bottom first):
    --overlay graphics/kc-short1-title.mov --overlay graphics/kc-short1-cap.mov

--y is the bubble's centre, measured from the top like captions_overlay.py's
--y. The default 0.565 sits it just above a caption at 0.65 and below the chin
on a mid-shot. --style brand = navy on Silicon Data green; white = black on white;
card = the long-form speaker card look (use --size 60, sentence case kept).
"""
import argparse, html, os, shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FONT = os.path.join(ROOT, "graphics", "fonts", "BebasNeue-Regular.ttf")
STYLES = {"brand": ("#00DE88", "#232234"), "white": ("#FFFFFF", "#000000")}
WIPE = 0.35

PAGE = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={w}, height={h}" />
    <title>short title</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      @font-face {{ font-family: "Bebas Neue"; src: url("BebasNeue-Regular.ttf") format("truetype"); }}
      * {{ margin:0; padding:0; box-sizing:border-box; }}
      html, body {{ width:{w}px; height:{h}px; overflow:hidden; background:transparent; }}
      #root {{ position:relative; width:{w}px; height:{h}px; }}
      .head {{ position:absolute; left:0; right:0; top:{y}%; transform:translateY(-50%);
               display:flex; flex-direction:column; align-items:center; gap:3px; }}
      .line {{ background:{bg}; color:{fg}; font-family:"Bebas Neue", sans-serif;
               font-size:{size}px; line-height:0.86; padding:14px 22px 3px; letter-spacing:0.01em;
               white-space:nowrap; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{dur}"
         data-width="{w}" data-height="{h}" data-fps="24000/1001">
      <div class="head">
{lines}
      </div>
    </div>
    <script>
      // GENERATED by edit/title_overlay.py — do not hand-edit.
      window.__timelines = window.__timelines || {{}};
      const tl = gsap.timeline({{ paused: true }});
      tl.fromTo(".line", {{ clipPath: "inset(0% 100% 0% 0%)" }},
                {{ clipPath: "inset(0% 0% 0% 0%)", duration: {wipe}, ease: "expo.out", stagger: 0.08 }}, 0);
      tl.set("#root", {{ opacity: 1 }}, {dur});
      tl.seek(0);
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
"""

CARD_FONT = os.path.join(ROOT, "graphics", "fonts", "Figtree.ttf")

# --style card: the long-form speaker card (edit/speaker_cards.py) shrunk for a
# phone — white plate, Index Blue gradient bar, black/blue corner tab, bold Figtree.
# Her ask 2026-11-05: "a little card above the captions with the title... in the
# style of the long form speaker card... not too big, middle of the screen below
# the speaker's face", two rows, captions moved below it.
CARD = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={w}, height={h}" />
    <title>short title card</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      @font-face {{ font-family: "Figtree"; src: url("Figtree.ttf") format("truetype"); font-weight: 300 900; }}
      * {{ margin:0; padding:0; box-sizing:border-box; }}
      html, body {{ width:{w}px; height:{h}px; overflow:hidden; background:transparent; }}
      #root {{ position:relative; width:{w}px; height:{h}px; }}
      .wrap {{ position:absolute; left:0; right:0; top:{y}%; transform:translateY(-50%);
               display:flex; justify-content:center; }}
      .card {{ position:relative; font-family:"Figtree", sans-serif; }}
      .bar {{ height:{bar}px; margin-left:{bar}px;
              background:linear-gradient(90deg, #EEF2FC 0%, #7D9BE6 22%, #3A66D8 50%, #2151D1 100%); }}
      .tab {{ position:absolute; left:0; top:0; width:{bar}px; height:{tab}px; z-index:2;
              background:linear-gradient(#000 0 50%, #2151D1 50% 100%); transform-origin:top; }}
      .plate {{ background:#fff; padding:{pt}px {pr}px {pb}px {pl}px; }}
      .line {{ font-weight:700; font-size:{size}px; line-height:1.08; letter-spacing:-0.01em;
               color:#000; white-space:nowrap; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{dur}"
         data-width="{w}" data-height="{h}" data-fps="24000/1001">
      <div class="wrap"><div class="card">
        <div class="bar"></div><div class="tab"></div>
        <div class="plate">
{lines}
        </div>
      </div></div>
    </div>
    <script>
      // GENERATED by edit/title_overlay.py — do not hand-edit.
      window.__timelines = window.__timelines || {{}};
      const tl = gsap.timeline({{ paused: true }});
{anim}      tl.set("#root", {{ opacity: 1 }}, {dur});
      tl.seek(0);
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
"""


# Optional wipe-in. Off by default: she wants the title there from the first frame,
# "no transition, just have it there from the start" (2026-11-06).
WIPE_IN = """      tl.fromTo(".bar", {{ clipPath: "inset(0% 100% 0% 0%)" }}, {{ clipPath: "inset(0% 0% 0% 0%)", duration: 0.55, ease: "expo.out" }}, {t0});
      tl.fromTo(".tab", {{ scaleY: 0 }}, {{ scaleY: 1, duration: 0.25, ease: "power3.out" }}, {t0});
      tl.fromTo(".plate", {{ clipPath: "inset(0% 100% 0% 0%)" }}, {{ clipPath: "inset(0% 0% 0% 0%)", duration: 0.55, ease: "expo.out" }}, {t1});
      tl.fromTo(".line", {{ x: -24, opacity: 0 }}, {{ x: 0, opacity: 1, duration: 0.5, ease: "power3.out", stagger: 0.06 }}, {t2});
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lines", nargs=2, required=True)
    ap.add_argument("--frames", type=int, required=True, help="frame count of the short's proof")
    ap.add_argument("--fps", type=float, default=24000 / 1001)
    ap.add_argument("--out", required=True)
    ap.add_argument("--y", type=float, default=0.565)
    ap.add_argument("--size", type=int, default=96)
    ap.add_argument("--style", choices=[*STYLES, "card"], default="brand")
    ap.add_argument("--res", default="1080x1920")
    ap.add_argument("--wipe", dest="still", action="store_false",
                    help="card style: wipe in at --delay instead of being on screen from frame 0")
    ap.add_argument("--delay", type=float, default=0.6,
                    help="card style: when the wipe-in starts. At 0 it is over before the short has begun and reads as no transition")
    a = ap.parse_args()
    w, h = map(int, a.res.split("x"))
    os.makedirs(a.out, exist_ok=True)
    dur = round(a.frames / a.fps, 3)
    if a.style == "card":
        shutil.copy(CARD_FONT, a.out)
        k = a.size / 60                      # laid out at 60px type
        lines = "\n".join(f'          <div class="line">{html.escape(l)}</div>' for l in a.lines)
        with open(os.path.join(a.out, "index.html"), "w") as fh:
            anim = "" if a.still else WIPE_IN.format(t0=a.delay, t1=round(a.delay + 0.08, 3), t2=round(a.delay + 0.16, 3))
            fh.write(CARD.format(anim=anim, w=w, h=h, y=round(a.y * 100, 2), size=a.size, dur=dur, lines=lines,
                                 bar=round(16 * k), tab=round(32 * k), pt=round(12 * k),
                                 pr=round(30 * k), pb=round(20 * k), pl=round(24 * k)))
        print(f"wrote {a.out}/index.html  ({a.frames} frames, style card, y {a.y})")
        return
    bg, fg = STYLES[a.style]
    shutil.copy(FONT, a.out)
    lines = "\n".join(f'        <div class="line">{html.escape(l.upper())}</div>' for l in a.lines)
    with open(os.path.join(a.out, "index.html"), "w") as fh:
        fh.write(PAGE.format(w=w, h=h, y=round(a.y * 100, 2), bg=bg, fg=fg, size=a.size,
                             dur=round(a.frames / a.fps, 3), wipe=WIPE, lines=lines))
    print(f"wrote {a.out}/index.html  ({a.frames} frames, style {a.style}, y {a.y})")


if __name__ == "__main__":
    main()
